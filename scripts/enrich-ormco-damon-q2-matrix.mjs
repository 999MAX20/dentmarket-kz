function stableId(parentId, sku) {
  const hash = createHash("sha256").update(`${parentId}:${sku}`).digest("hex").slice(0, 24);
  return `${parentId}-variant-${hash}`;
}

function buildVariant(product, row) {
  const [sku, jaw, tooth, side, torque, angulation, rotation, prescription, hook] = row;
  const each = sku.startsWith("161-");
  return {
    id: stableId(product.id, sku),
    sku,
    gtin: null,
    label: `${jaw} челюсть · ${tooth} · ${side.toLowerCase()} · ${prescription.toLowerCase()} торк ${torque} · ${hook.toLowerCase()} · ${each ? "1 шт." : "10 шт."}`,
    attributes: {
      "Система": "Damon Q2",
      "Материал": "Металл",
      "Тип брекетов": "Самолигирующие",
      "Формат продажи": each ? "Позиционный брекет" : "Упаковка позиционных брекетов",
      "Количество": each ? "1 шт." : "10 шт.",
      "Пропись": prescription,
      "Паз": "0.022″",
      "Челюсть": jaw,
      "Позиция зуба": `${tooth}, ${side.toLowerCase()}`,
      "Сторона": side,
      "Торк": torque,
      "Ангуляция": angulation,
      "Ротация": rotation,
      "Крючок": hook,
      "Артикул производителя": sku,
    },
    imageUrl: product.imageUrl,
    sourceUrl: officialCatalogUrl,
  };
}

let changedFiles = 0;
let addedVariants = 0;
for (const file of files) {
  const document = JSON.parse(await readFile(file, "utf8"));
  const products = Array.isArray(document) ? document : document.products;
  const product = products.find(
    (item) =>
      item.canonicalProductId === "CANON-ORMCO-DAMON-Q2" ||
      /\bORMCO Damon Q2\b/i.test(item.name ?? ""),
  );
  if (!product) continue;
  const verifiedBySku = new Map(rows.map((row) => [row[0], buildVariant(product, row)]));
  const untouched = (product.variants ?? [])
    .filter((variant) => !variant.sku || !verifiedBySku.has(variant.sku))
    .map((variant) => {
      if (variant.sku || variant.attributes?.["Челюсть"]) return variant;
      const source = (product.sourceVariants ?? []).find((item) =>
        variant.id?.startsWith(`${item.productId}-variant-`),
      );
      const sourceName = source?.name ?? "";
      const jaw = /НЧ/i.test(sourceName)
        ? "Нижняя"
        : /ВЧ/i.test(sourceName)
          ? "Верхняя"
          : null;
      if (!jaw) return variant;
      return {
        ...variant,
        label: `${jaw} челюсть · ${variant.label}`,
        attributes: { ...(variant.attributes ?? {}), "Челюсть": jaw },
      };
    });
  const additions = [...verifiedBySku.values()];
  product.variants = [...untouched, ...additions];
  product.aliases = [
    ...new Set([
      ...(product.aliases ?? []),
      "отдельные брекеты Damon Q2",
      "позиционные брекеты Damon Q2",
      "Damon Q2 .022",
      ...rows.map(([sku]) => sku),
    ]),
  ];
  product.moderationWarnings = (product.moderationWarnings ?? []).filter(
    (warning) => warning !== "EXACT_POSITION_SKU_MATRIX_REQUIRED",
  );
  product.commerceModel = {
    ...(product.commerceModel ?? {}),
    grain: "Бренд + система; наборы и позиционные упаковки выбираются вариантами",
    status: "POSITION_SKU_MATRIX_VERIFIED",
    officialMatrixSource: officialCatalogUrl,
    verifiedPositionVariantCount: rows.length,
  };
  addedVariants += additions.length;
  changedFiles += 1;
  await writeFile(file, `${JSON.stringify(document, null, 2)}\n`);
}

